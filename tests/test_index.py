"""Tests for data/openapi-index.json.

The index is generated by scripts/probe.py from live probe reports, so it cannot be
rebuilt in CI. These tests check that what is committed is internally consistent and
still points at rows that exist in the catalog.

Run from the repository root:
    python -m unittest tests.test_catalog tests.test_probe tests.test_export tests.test_index -v
"""
import importlib.util
import json
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INDEX = ROOT / "data" / "openapi-index.json"


def _load_catalog():
    if "catalog" in sys.modules:
        return sys.modules["catalog"]
    spec = importlib.util.spec_from_file_location("catalog", ROOT / "scripts" / "catalog.py")
    module = importlib.util.module_from_spec(spec)
    sys.modules["catalog"] = module
    spec.loader.exec_module(module)
    return module


catalog = _load_catalog()
DATA = json.loads(INDEX.read_text(encoding="utf-8"))
ENTRIES = DATA["entries"]


class SpecIndex(unittest.TestCase):
    def test_counts_are_consistent(self):
        self.assertEqual(DATA["specs"], len(ENTRIES))
        self.assertGreater(DATA["entries_probed"], 0)
        self.assertLessEqual(DATA["specs"], DATA["entries_probed"])
        self.assertIn("generated", DATA)
        self.assertIn("Absence is not proof", DATA["description"])

    def test_every_spec_points_at_a_catalogued_row(self):
        entries = catalog.load(catalog.Problems(), strict=True)
        by_key = {(e.category, e.name) for e in entries}
        missing = [(e["category"], e["name"]) for e in ENTRIES
                   if (e["category"], e["name"]) not in by_key]
        self.assertEqual(missing, [], f"index rows no longer in the catalog: {missing[:10]}")

    def test_each_spec_is_well_formed(self):
        failures = []
        for entry in ENTRIES:
            for field in ("name", "category", "website", "spec_url", "spec_version", "path_count"):
                if entry.get(field) in (None, ""):
                    failures.append(f"{entry.get('name')}: missing {field}")
            if not str(entry.get("spec_url", "")).startswith(("http://", "https://")):
                failures.append(f"{entry.get('name')}: spec_url is not a URL")
            if not isinstance(entry.get("path_count"), int) or entry["path_count"] < 1:
                failures.append(f"{entry.get('name')}: path_count must be a positive integer")
        self.assertEqual(failures, [], "\n".join(failures[:10]))

    def test_no_duplicate_rows(self):
        keys = [(e["category"], e["name"]) for e in ENTRIES]
        self.assertEqual(len(keys), len(set(keys)))


if __name__ == "__main__":
    unittest.main()
